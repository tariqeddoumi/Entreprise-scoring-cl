/** Libellé d'une action ; à défaut, le code rendu lisible. */
export function auditLabel(action: string): string {
  return AUDIT_ACTION_LABELS[action] ?? action.charAt(0) + action.slice(1).toLowerCase().replace(/_/g, " ");
}
